class Html(str):
    """Marks a string as already-safe HTML."""


def esc(value) -> str:
    if isinstance(value, Html):
        return value
    return _html.escape("" if value is None else str(value), quote=True)


def safe_url(url) -> str:
    u = str(url or "").strip()
    return u if u.lower().startswith(("http://", "https://")) else ""


def link(url, text=None) -> Html:
    u = safe_url(url)
    if not u:
        return Html(esc(text or ""))
    return Html('<a href="%s" rel="noopener noreferrer" target="_blank">%s</a>' % (esc(u), esc(text or u)))


def _color(c) -> str:
    return COLORS.get(c, c or COLORS["gray"])


def page(title: str, body: str, subtitle: str = "", asset=None, extra_head: str = "") -> str:
    meme = "meme" in (asset if isinstance(asset, (list, tuple, set)) else [asset])
    return ("<!doctype html><html lang='en'><head><meta charset='utf-8'>"
            "<meta name='viewport' content='width=device-width,initial-scale=1'>"
            "<title>%s</title><style>%s</style>%s</head><body><div class='wrap'>"
            "<header><h1>%s</h1><div class='sub'>%s</div></header>%s"
            "<div class='disclaimer%s'>%s</div>"
            "<div class='sub' style='margin-top:10px'>Generated by Trader · %s</div>"
            "</div></body></html>") % (
        esc(title), CSS, extra_head, esc(title), esc(subtitle), body, " meme" if meme else "",
        esc(disclaimer.text(asset)), esc(market_clock.iso(market_clock.now_utc())))


def tiles(items) -> str:
    """items: (label, value, tone) with tone in good|bad|warn|info|''"""
    out = ["<div class='tiles'>"]
    for item in items:
        label, value = item[0], item[1]
        tone = item[2] if len(item) > 2 else ""
        out.append("<div class='tile %s'><div class='k'>%s</div><div class='v'>%s</div></div>"
                   % (esc(tone), esc(label), esc(value)))
    out.append("</div>")
    return "".join(out)


def card(title: str, inner: str) -> str:
    return "<section class='card'>%s%s</section>" % ("<h2>%s</h2>" % esc(title) if title else "", inner)


def table(headers, rows) -> str:
    head = "".join("<th>%s</th>" % esc(h) for h in headers)
    body = "".join("<tr>%s</tr>" % "".join("<td>%s</td>" % esc(c) for c in r) for r in rows)
    return "<div class='table-wrap'><table><thead><tr>%s</tr></thead><tbody>%s</tbody></table></div>" % (head, body)


def pill(text, tone="") -> Html:
    return Html("<span class='pill %s'>%s</span>" % (esc(tone), esc(text)))


def write_report(name: str, html_text: str) -> Path:
    p = state.path("reports", name)
    tmp = p.with_name(p.name + ".tmp")
    tmp.write_text(html_text, encoding="utf-8")
    tmp.replace(p)
    return p


