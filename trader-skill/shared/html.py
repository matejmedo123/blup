def _nice_ticks(lo: float, hi: float, n: int = 5) -> list:
    if hi <= lo:
        hi = lo + (abs(lo) * 0.01 or 1.0)
    raw = (hi - lo) / max(n, 1)
    mag = 10 ** math.floor(math.log10(raw))
    for m in (1, 2, 2.5, 5, 10):
        if raw <= m * mag:
            step = m * mag
            break
    start = math.ceil(lo / step) * step
    ticks = []
    v = start
    while v <= hi + 1e-12 and len(ticks) < 20:
        ticks.append(v)
        v += step
    return ticks


def _spread_labels(ys, min_gap: float, top: float, bottom: float) -> list:
    """Push overlapping right-edge labels apart vertically, keeping order."""
    order = sorted(range(len(ys)), key=lambda i: ys[i])
    out = list(ys)
    last = None
    for i in order:
        y = max(out[i], top)
        if last is not None and y - last < min_gap:
            y = last + min_gap
        out[i] = y
        last = y
    over = (last or 0) - bottom
    if over > 0:
        for i in order:
            out[i] -= over
    return out


def _time_label(t: int, asset: str, multi_day: bool) -> str:
    if asset == "stock":
        e = market_clock.to_et(t)
        return ("%s %d" % (e.strftime("%b"), e.day)) if multi_day and (e.hour, e.minute) == (9, 30) else \
            market_clock.fmt_et(t)
    u = market_clock.from_ts(t)
    return u.strftime("%b %d") if multi_day and u.hour == 0 and u.minute == 0 else u.strftime("%H:%M")


def candle_chart(candles, lines=(), markers=(), shades=(), width: int = 960, height: int = 400,
                 asset: str = "stock", title: str = "", compact: bool = False, show_volume: bool = True) -> str:
    candles = list(candles)
    if not candles:
        return "<p class='muted'>no candles</p>"
    pad_l, pad_r = (8, 8) if compact else (64, 132)
    pad_t, pad_b = (6, 6) if compact else (14, 26)
    vol_h = 0 if (compact or not show_volume) else int(height * 0.16)
    plot_h = height - pad_t - pad_b - vol_h
    plot_w = width - pad_l - pad_r
    lows = [c.l for c in candles] + [ln["price"] for ln in lines if ln.get("price")]
    highs = [c.h for c in candles] + [ln["price"] for ln in lines if ln.get("price")]
    lo, hi = min(lows), max(highs)
    span = (hi - lo) or (abs(hi) * 0.01 or 1)
    lo -= span * 0.04
    hi += span * 0.04
    n = len(candles)
    bw = plot_w / float(n)

    def x(i):
        return pad_l + (i + 0.5) * bw

    def y(p):
        return pad_t + (hi - p) / (hi - lo) * plot_h
    out = ["<svg viewBox='0 0 %d %d' role='img' aria-label='%s'>" % (width, height, esc(title or "candlestick chart"))]
    out.append("<rect x='0' y='0' width='%d' height='%d' fill='#fff'/>" % (width, height))
    if not compact:
        for tv in _nice_ticks(lo, hi, 6):
            yy = y(tv)
            out.append("<line x1='%d' x2='%d' y1='%.1f' y2='%.1f' stroke='#edf0f3'/>" % (pad_l, width - pad_r, yy, yy))
            out.append("<text x='%d' y='%.1f' text-anchor='end'>%s</text>" % (pad_l - 6, yy + 4, esc(fmt.price(tv))))
    index_of = {c.t: i for i, c in enumerate(candles)}
    for s in shades:
        idx = [i for i, c in enumerate(candles) if s["t0"] <= c.t < s["t1"]]
        if idx:
            x0 = pad_l + idx[0] * bw
            x1 = pad_l + (idx[-1] + 1) * bw
            out.append("<rect x='%.1f' y='%d' width='%.1f' height='%d' fill='%s' opacity='0.08'/>"
                       % (x0, pad_t, x1 - x0, plot_h, _color(s.get("color", "blue"))))
            if s.get("label") and not compact:
                out.append("<text x='%.1f' y='%d'>%s</text>" % (x0 + 3, pad_t + 12, esc(s["label"])))
    vmax = max((c.v for c in candles), default=0) or 1
    for i, c in enumerate(candles):
        col = UP if c.c >= c.o else DOWN
        xx = x(i)
        out.append("<line x1='%.1f' x2='%.1f' y1='%.1f' y2='%.1f' stroke='%s' stroke-width='1'/>"
                   % (xx, xx, y(c.h), y(c.l), col))
        top, bot = y(max(c.o, c.c)), y(min(c.o, c.c))
        out.append("<rect x='%.1f' y='%.1f' width='%.2f' height='%.1f' fill='%s'/>"
                   % (xx - max(bw * 0.35, 0.5), top, max(bw * 0.7, 1.0), max(bot - top, 0.8), col))
        if vol_h:
            vh = c.v / vmax * (vol_h - 4)
            out.append("<rect x='%.1f' y='%.1f' width='%.2f' height='%.1f' fill='%s' opacity='0.28'/>"
                       % (xx - max(bw * 0.35, 0.5), height - pad_b - vh, max(bw * 0.7, 1.0), vh, col))
    if not compact:
        days = {(market_clock.et_date(c.t) if asset == "stock" else market_clock.from_ts(c.t).date()) for c in candles}
        multi = len(days) > 1
        ticks = max(2, min(8, int(plot_w // 110)))
        for k in range(ticks):
            i = int(round(k * (n - 1) / float(ticks - 1)))
            out.append("<text x='%.1f' y='%d' text-anchor='middle'>%s</text>"
                       % (x(i), height - 8, esc(_time_label(candles[i].t, asset, multi))))
    label_ys = []
    for ln in lines:
        yy = y(ln["price"])
        dash = " stroke-dasharray='5 4'" if ln.get("dash") else ""
        out.append("<line x1='%d' x2='%d' y1='%.1f' y2='%.1f' stroke='%s' stroke-width='%s'%s/>"
                   % (pad_l, width - pad_r, yy, yy, _color(ln.get("color")), "1.4" if not compact else "1", dash))
        label_ys.append(yy)
    if lines and not compact:
        spread = _spread_labels(label_ys, 14, pad_t + 8, pad_t + plot_h)
        for ln, ly in zip(lines, spread):
            text = "%s %s" % (ln.get("label", ""), fmt.price(ln["price"]))
            out.append("<text x='%d' y='%.1f' style='fill:%s;font-weight:600'>%s</text>"
                       % (width - pad_r + 6, ly + 4, _color(ln.get("color")), esc(text.strip())))
    for m in markers:
        i = index_of.get(m["t"])
        if i is None:
            continue
        xx, yy = x(i), y(m["price"])
        col = _color(m.get("color", "blue"))
        if m.get("shape", "up") == "up":
            pts = "%.1f,%.1f %.1f,%.1f %.1f,%.1f" % (xx, yy + 4, xx - 6, yy + 14, xx + 6, yy + 14)
        elif m.get("shape") == "down":
            pts = "%.1f,%.1f %.1f,%.1f %.1f,%.1f" % (xx, yy - 4, xx - 6, yy - 14, xx + 6, yy - 14)
        else:
            out.append("<circle cx='%.1f' cy='%.1f' r='4' fill='%s'/>" % (xx, yy, col))
            pts = None
        if pts:
            out.append("<polygon points='%s' fill='%s'/>" % (pts, col))
        if m.get("label") and not compact:
            out.append("<text x='%.1f' y='%.1f' text-anchor='middle' style='fill:%s;font-weight:600'>%s</text>"
                       % (xx, yy + (28 if m.get("shape", "up") == "up" else -20), col, esc(m["label"])))
    out.append("</svg>")
    return "".join(out)


def mini_chart(candles, lines=(), markers=(), width: int = 300, height: int = 120, asset: str = "stock") -> str:
    return candle_chart(candles, lines, markers, (), width, height, asset, compact=True)


def histogram(values, bins: int = 40, lines=(), width: int = 960, height: int = 300, tone=None,
              title: str = "") -> str:
    vals = sorted(v for v in values if v is not None and math.isfinite(v))
    if not vals:
        return "<p class='muted'>no data</p>"
    lo, hi = vals[0], vals[-1]
    for ln in lines:
        lo, hi = min(lo, ln["price"]), max(hi, ln["price"])
    span = (hi - lo) or 1.0
    lo -= span * 0.02
    hi += span * 0.02
    edges = [lo + (hi - lo) * k / bins for k in range(bins + 1)]
    counts = [0] * bins
    for v in vals:
        k = min(bins - 1, int((v - lo) / (hi - lo) * bins))
        counts[k] += 1
    pad_l, pad_r, pad_t, pad_b = 48, 16, 26, 34
    pw, ph = width - pad_l - pad_r, height - pad_t - pad_b
    cmax = max(counts) or 1

    def x(p):
        return pad_l + (p - lo) / (hi - lo) * pw
    out = ["<svg viewBox='0 0 %d %d' role='img' aria-label='%s'>" % (width, height, esc(title or "histogram"))]
    out.append("<rect width='%d' height='%d' fill='#fff'/>" % (width, height))
    for k, cnt in enumerate(counts):
        mid = (edges[k] + edges[k + 1]) / 2
        col = _color(tone(mid) if tone else "blue")
        bh = cnt / float(cmax) * ph
        out.append("<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' fill='%s' opacity='0.75'/>"
                   % (x(edges[k]) + 0.5, pad_t + ph - bh, max(pw / bins - 1, 0.5), bh, col))
    for tv in _nice_ticks(lo, hi, 7):
        out.append("<text x='%.1f' y='%d' text-anchor='middle'>%s</text>" % (x(tv), height - 10, esc(fmt.price(tv))))
    for frac in (0.5, 1.0):
        yy = pad_t + ph - frac * ph
        out.append("<text x='%d' y='%.1f' text-anchor='end'>%d</text>" % (pad_l - 6, yy + 4, int(cmax * frac)))
    labels = []
    for ln in lines:
        xx = x(ln["price"])
        out.append("<line x1='%.1f' x2='%.1f' y1='%d' y2='%d' stroke='%s' stroke-width='1.6'%s/>"
                   % (xx, xx, pad_t - 4, pad_t + ph, _color(ln.get("color")),
                      " stroke-dasharray='5 4'" if ln.get("dash") else ""))
        labels.append((xx, ln))
    labels.sort(key=lambda a: a[0])
    last_x = -1e9
    row = 0
    for xx, ln in labels:
        row = row + 1 if xx - last_x < 120 else 0
        out.append("<text x='%.1f' y='%d' text-anchor='middle' style='fill:%s;font-weight:600'>%s</text>"
                   % (xx, 12 + row * 12, _color(ln.get("color")), esc("%s %s" % (ln.get("label", ""), fmt.price(ln["price"])))))
        last_x = xx
    out.append("</svg>")
    return "".join(out)


def fan_chart(paths, lines=(), x_labels=(), width: int = 960, height: int = 380, counter_total: int = None,
              chart_id: str = "fan", title: str = "") -> str:
    """paths: [{"prices": [...], "outcome": "target|stop|neither|rug"}]. Optional animated counter."""
    if not paths:
        return "<p class='muted'>no paths</p>"
    steps = max(len(p["prices"]) for p in paths)
    allp = [v for p in paths for v in p["prices"]] + [ln["price"] for ln in lines]
    lo, hi = min(allp), max(allp)
    span = (hi - lo) or 1.0
    lo -= span * 0.03
    hi += span * 0.03
    pad_l, pad_r, pad_t, pad_b = 64, 132, 12, 26
    pw, ph = width - pad_l - pad_r, height - pad_t - pad_b

    def x(i):
        return pad_l + i / float(max(steps - 1, 1)) * pw

    def y(p):
        return pad_t + (hi - p) / (hi - lo) * ph
    col = {"target": COLORS["green"], "stop": COLORS["red"], "neither": COLORS["blue"], "rug": COLORS["purple"]}
    out = ["<svg id='%s' viewBox='0 0 %d %d' role='img' aria-label='%s'>" % (esc(chart_id), width, height,
                                                                             esc(title or "simulated paths"))]
    out.append("<rect width='%d' height='%d' fill='#fff'/>" % (width, height))
    for tv in _nice_ticks(lo, hi, 6):
        yy = y(tv)
        out.append("<line x1='%d' x2='%d' y1='%.1f' y2='%.1f' stroke='#edf0f3'/>" % (pad_l, width - pad_r, yy, yy))
        out.append("<text x='%d' y='%.1f' text-anchor='end'>%s</text>" % (pad_l - 6, yy + 4, esc(fmt.price(tv))))
    for k, p in enumerate(paths):
        pts = " ".join("%.1f,%.1f" % (x(i), y(v)) for i, v in enumerate(p["prices"]))
        out.append("<polyline class='p' data-k='%d' points='%s' fill='none' stroke='%s' stroke-width='1' "
                   "opacity='0.28'/>" % (k, pts, col.get(p.get("outcome"), COLORS["gray"])))
    label_ys = []
    for ln in lines:
        yy = y(ln["price"])
        out.append("<line x1='%d' x2='%d' y1='%.1f' y2='%.1f' stroke='%s' stroke-width='1.6'%s/>"
                   % (pad_l, width - pad_r, yy, yy, _color(ln.get("color")),
                      " stroke-dasharray='5 4'" if ln.get("dash") else ""))
        label_ys.append(yy)
    for ln, ly in zip(lines, _spread_labels(label_ys, 14, pad_t + 8, pad_t + ph)):
        out.append("<text x='%d' y='%.1f' style='fill:%s;font-weight:600'>%s</text>"
                   % (width - pad_r + 6, ly + 4, _color(ln.get("color")),
                      esc("%s %s" % (ln.get("label", ""), fmt.price(ln["price"])))))
    labels = list(x_labels)
    if labels:
        ticks = max(2, min(7, int(pw // 120)))
        for k in range(ticks):
            i = int(round(k * (len(labels) - 1) / float(ticks - 1)))
            out.append("<text x='%.1f' y='%d' text-anchor='middle'>%s</text>" % (x(i), height - 8, esc(labels[i])))
    out.append("</svg>")
    if counter_total:
        # progressive enhancement: without JS every path is visible and the counter shows the total
        out.append("<div class='counter' id='%s-counter'>%s simulated sessions</div>" % (
            esc(chart_id), fmt.count(counter_total)))
        out.append("<script>(function(){var s=document.getElementById(%s),c=document.getElementById(%s);"
                   "if(!s||!c||!window.requestAnimationFrame)return;var ps=s.querySelectorAll('.p'),n=ps.length,"
                   "total=%d,t0=null,dur=2600;for(var i=0;i<n;i++)ps[i].style.display='none';"
                   "function f(ts){if(t0===null)t0=ts;var k=Math.min(1,(ts-t0)/dur),shown=Math.floor(k*n);"
                   "for(var i=0;i<shown;i++)ps[i].style.display='';"
                   "c.textContent=Math.floor(k*total).toLocaleString('en-US')+' \\u2026 '+total.toLocaleString('en-US')"
                   "+' simulated sessions';if(k<1)requestAnimationFrame(f);}requestAnimationFrame(f);})();</script>"
                   % (json.dumps(chart_id), json.dumps(chart_id + "-counter"), int(counter_total)))
    return "".join(out)


def line_chart(values, width: int = 960, height: int = 220, color: str = "blue", zero_line: bool = True,
               x_labels=(), title: str = "", y_fmt=None) -> str:
    vals = [float(v) for v in values]
    if not vals:
        return "<p class='muted'>no data</p>"
    lo, hi = min(vals + ([0.0] if zero_line else [])), max(vals + ([0.0] if zero_line else []))
    span = (hi - lo) or 1.0
    lo -= span * 0.06
    hi += span * 0.06
    pad_l, pad_r, pad_t, pad_b = 56, 16, 12, 26
    pw, ph = width - pad_l - pad_r, height - pad_t - pad_b
    n = len(vals)

    def x(i):
        return pad_l + (i / float(max(n - 1, 1))) * pw

    def y(v):
        return pad_t + (hi - v) / (hi - lo) * ph
    y_fmt = y_fmt or (lambda v: "%+.1fR" % v)
    out = ["<svg viewBox='0 0 %d %d' role='img' aria-label='%s'>" % (width, height, esc(title or "line chart")),
           "<rect width='%d' height='%d' fill='#fff'/>" % (width, height)]
    for tv in _nice_ticks(lo, hi, 4):
        out.append("<line x1='%d' x2='%d' y1='%.1f' y2='%.1f' stroke='#edf0f3'/>" % (pad_l, width - pad_r, y(tv), y(tv)))
        out.append("<text x='%d' y='%.1f' text-anchor='end'>%s</text>" % (pad_l - 6, y(tv) + 4, esc(y_fmt(tv))))
    if zero_line:
        out.append("<line x1='%d' x2='%d' y1='%.1f' y2='%.1f' stroke='#8c959f' stroke-dasharray='3 3'/>"
                   % (pad_l, width - pad_r, y(0), y(0)))
    pts = " ".join("%.1f,%.1f" % (x(i), y(v)) for i, v in enumerate(vals))
    out.append("<polyline points='%s' fill='none' stroke='%s' stroke-width='2'/>" % (pts, _color(color)))
    labels = list(x_labels)
    if labels:
        ticks = max(2, min(7, int(pw // 120), len(labels)))
        for k in range(ticks):
            i = int(round(k * (len(labels) - 1) / float(max(ticks - 1, 1))))
            out.append("<text x='%.1f' y='%d' text-anchor='middle'>%s</text>" % (x(i), height - 8, esc(labels[i])))
    out.append("</svg>")
    return "".join(out)
