-- ============================================================================
-- Futbalový štadión a sektory, ktoré sa neprekrývajú
-- ============================================================================
-- Dve veci naraz, lebo obe sú v tom istom JSON-e.
--
-- 1. PREKRYVY. Oblúkové tribúny boli generované sweepom, ktorý presahoval do
--    susedného sektora: na štadióne mala každá tribúna 100° namiesto 90°, tak
--    v každom rohu ležali dve cez seba; v divadle balkón vybiehal hore do
--    parteru a v hale oblúk do bočných tribún. Sedem prekryvov dokopy.
--    Vyzerá to ako rohové bloky inej farby a pri predaji je to horšie než
--    škaredé — dve sedadlá na tom istom mieste.
--
--    Konce oblúka sa teraz režú vodorovne, nie radiálne: vnútorný aj vonkajší
--    oblúk končia na tej istej výške. Inak vnútorný koniec vždy vybehne vyššie
--    než vonkajší, a presne to spôsobilo prekryv v divadle.
--
-- 2. ŠTADIÓN. Štyri veľké oblúky nie sú futbalový štadión. Naozajstný má
--    ihrisko a okolo neho desiatky očíslovaných sektorov — A101, B204, C102 —
--    presne tie, ktoré má človek na lístku a hľadá ich na turnikete. Predloha
--    je prekreslená podľa toho: dva prstence tribún okolo ihriska — spodný
--    A101–A111, D101–D106, B101–B110, C101–C104, horný s lóžami V01–V07,
--    D201–D208, B201–B209, C201–C206 — skybox a štyri brány.
--
--    A nie sú to obdĺžniky. Sektor je výseč prstenca: na rovinke vyjde skoro
--    obdĺžnikový, v rohu sa zatáča spolu s tribúnou, tak ako stojí v hale.
--    Prstenec je superelipsa, nie kruh — štadión je zaoblený obdĺžnik a na
--    kruhu by polovica ihriska skončila v rohu. Sektory sa delia po dĺžke
--    oblúka, nie po uhle, inak by rohové vyšli citeľne menšie než tie na
--    rovinke.
--
--    67 sektorov a 4 920 sedadiel, ktoré sa generujú rovno pri nasadení
--    predlohy — organizátor už len prepisuje názvy a ceny.
--
-- Preto `apply_venue_preset` po novom pozná `rows`, `per_row` a `row_prefix`:
-- sektor, ktorý ich má, dostane miesta hneď. Sektor bez nich zostáva na počet,
-- ako doteraz — divadlo, kino aj klub sa nezmenili.
