-- ============================================================================
-- BLUP test 39 · The seat survives the sale
-- ============================================================================
-- Test 18 proved the plan and the hold. This proves the part that was missing
-- underneath it: that the chair the buyer picked is still theirs after the
-- basket becomes an order, after the payment page, and after the ticket is
-- issued — and that nobody else can be sold it at any point along the way.
--
-- What is actually being proved here:
--
--   · a held seat stays held when the basket turns into orders
--   · the paid ticket names the seat, so the door knows where to send them
--   · an abandoned checkout gives the seat back, without a sweep having to run
--   · a numbered sector cannot be bought without naming a seat — the hole the
--     guest checkout and the plain ticket list both walked straight through
--   · a seat cannot be bought through the wrong sector
--   · two live orders cannot name one seat, whatever the app does
--   · holding four seats is all-or-nothing
--   · "give me four together" gives four together, front and centre, and never
--     quietly hands out a wheelchair space
--   · regenerating a stand cannot delete a seat somebody paid for
--   · a sector can be renamed, and cannot be re-pointed once it has sold
--   · the door list knows who is in D14
-- ============================================================================
