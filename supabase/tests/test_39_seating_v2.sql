  assert dot ->> 'mine_claim' = 'sold', 'and it is sold, not merely held';
  assert not (dot ->> 'taken')::boolean, 'a seat I own is not "taken" from me';
  assert not (dot ->> 'free')::boolean, 'nor is it free';
