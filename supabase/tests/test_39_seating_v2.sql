-- 4. Two live orders, one chair
-- ============================================================================
do $$
declare
  buyer  uuid := 'a3939393-0000-0000-0000-000000000002';
  rival  uuid := 'a3939393-0000-0000-0000-000000000003';
  stalls uuid := 'c3939393-0000-0000-0000-000000000001';
  seat   uuid;
  ord    public.orders;
begin
  select id into seat from public.venue_seats
  where venue_section_id = 'b3939393-0000-0000-0000-000000000001'
    and row_label = 'A' and seat_number = 2;

  ord := public.create_order(buyer, stalls, 1, null, null, null, null, null, null, null, null, null, seat);
  assert ord.venue_seat_id = seat, 'the order carries the seat';

  -- The function's own check should catch this. The index is what catches it
  -- when two of these run at the same instant, so both are worth proving.
  begin
    ord := public.create_order(rival, stalls, 1, null, null, null, null, null, null, null, null, null, seat);
    assert false, 'a seat on a live order must not be orderable again';
  exception when others then
    assert sqlerrm in ('SEAT_TAKEN', 'duplicate key value violates unique constraint "orders_seat_once"')
        or sqlerrm like '%orders_seat_once%',
      format('expected the seat to be refused, got %s', sqlerrm);
  end;
  raise notice 'PASS one chair cannot be on two live orders';

  -- Cancelled, and it is back.
  update public.orders set payment_status = 'cancelled' where venue_seat_id = seat;
  ord := public.create_order(rival, stalls, 1, null, null, null, null, null, null, null, null, null, seat);
  assert ord.venue_seat_id = seat, 'a cancelled order releases its seat';
  update public.orders set payment_status = 'cancelled' where venue_seat_id = seat;
  raise notice 'PASS a cancelled order puts the chair back on sale';

  -- And three of one chair is not a thing.
  begin
    ord := public.create_order(buyer, stalls, 3, null, null, null, null, null, null, null, null, null, seat);
    assert false, 'three of seat A2 is not a purchase';
  exception when others then
    assert sqlerrm = 'SEAT_IS_SINGLE', format('expected SEAT_IS_SINGLE, got %s', sqlerrm);
  end;
  raise notice 'PASS a seat is one seat';
end $$;


-- ============================================================================
-- 5. Four seats, all or nothing
-- ============================================================================
do $$
declare
  buyer uuid := 'a3939393-0000-0000-0000-000000000002';
  rival uuid := 'a3939393-0000-0000-0000-000000000003';
  wanted uuid[];
  blocked uuid;
  n integer;
begin
  select array_agg(id order by seat_number) into wanted
  from public.venue_seats
  where venue_section_id = 'b3939393-0000-0000-0000-000000000001'
    and row_label = 'C' and seat_number between 2 and 5;

  blocked := wanted[3];

  perform set_config('request.jwt.claim.sub', rival::text, true);
  perform public.cart_hold_seat(blocked);

  perform set_config('request.jwt.claim.sub', buyer::text, true);
  begin
    perform public.cart_hold_seats(wanted);
    assert false, 'one seat gone must fail the whole set';
  exception when others then
    assert sqlerrm = 'SEAT_HELD', format('expected SEAT_HELD, got %s', sqlerrm);
  end;

  select count(*) into n from public.cart_items where user_id = buyer and expires_at > now();
  assert n = 0, format('nothing may be held when the set fails, got %s', n);
  raise notice 'PASS holding four seats is all of them or none';

  -- The rival lets go, and now the whole row is free.
  perform public.cart_release_seat(blocked);   -- runs as buyer: not theirs
  assert exists (select 1 from public.cart_items where venue_seat_id = blocked),
    'releasing somebody else''s seat does nothing';

  perform set_config('request.jwt.claim.sub', rival::text, true);
  perform public.cart_release_seat(blocked);

  perform set_config('request.jwt.claim.sub', buyer::text, true);
  perform public.cart_hold_seats(wanted);
  select count(*) into n from public.cart_items where user_id = buyer and expires_at > now();
  assert n = 4, format('four seats, four lines, got %s', n);

  -- Clicking the same four again is impatience, not an error.
  perform public.cart_hold_seats(wanted);
  select count(*) into n from public.cart_items where user_id = buyer and expires_at > now();
  assert n = 4, format('re-holding the same four changes nothing, got %s', n);
  raise notice 'PASS four seats in one go, and asking twice is not an error';

  perform public.cart_clear();
end $$;


-- ============================================================================
-- 6. "Give me four together"
-- ============================================================================
do $$
declare
  buyer   uuid := 'a3939393-0000-0000-0000-000000000002';
  stalls  uuid := 'b3939393-0000-0000-0000-000000000001';
  picked  record;
  rows_n  integer;
  labels  text[];
  numbers integer[];
begin
  -- An empty house: the best four are in the front row, in the middle.
  select array_agg(s.row_label order by s.seat_number),
         array_agg(s.seat_number order by s.seat_number)
    into labels, numbers
  from public.suggest_seats(stalls, 4) s;

  assert array_length(labels, 1) = 4, 'four asked for, four offered';
  select count(distinct l) into rows_n from unnest(labels) l;
  assert rows_n = 1, 'and all in one row';
  assert labels[1] = 'A', format('the front row first, got %s', labels[1]);
  assert numbers = array[2, 3, 4, 5],
    format('and centred in a row of six, got %s', numbers::text);
  raise notice 'PASS the suggestion is four together, front and centre';

  -- Take the middle of row A out, and the answer moves to the next row rather
  -- than splitting the group.
  perform set_config('request.jwt.claim.sub', buyer::text, true);
  perform public.cart_hold_seat((select id from public.venue_seats
    where venue_section_id = stalls and row_label = 'A' and seat_number = 3));

  select array_agg(s.row_label order by s.seat_number),
         array_agg(s.seat_number order by s.seat_number)
    into labels, numbers
  from public.suggest_seats(stalls, 4) s;

  select count(distinct l) into rows_n from unnest(labels) l;
  assert rows_n = 1, 'the group is still kept together';
  -- Row A has a hole in the middle now, and row B lost seat 3 to the sale at
  -- the top of this file — so the first row that can still seat four is C.
  assert labels[1] = 'C', format('expected the group moved back to row C, got %s', labels[1]);
  raise notice 'PASS the group is moved back a row rather than split up';

  perform public.cart_clear();

  -- A wheelchair space is never handed out as one of a block.
  perform set_config('request.jwt.claim.sub', 'a3939393-0000-0000-0000-000000000009', true);
  perform public.set_seat_state(
    array[(select id from public.venue_seats
           where venue_section_id = stalls and row_label = 'A' and seat_number = 4)],
    null, 'wheelchair', 'Miesto pre vozík');

  select array_agg(s.seat_number order by s.seat_number) into numbers
  from public.suggest_seats(stalls, 3) s
  where s.row_label = 'A';
  assert numbers is null or not (4 = any (numbers)),
    'a wheelchair space must never be handed out as part of a block';
  raise notice 'PASS an accessible seat is not quietly sold to a group of three';

  -- And a group too big for the room is told so, rather than offered less.
  assert not exists (select 1 from public.suggest_seats(stalls, 9)),
    'nine together in a row of six is nothing, not "here are six"';
  raise notice 'PASS a group that cannot sit together is told nothing, not fobbed off';
end $$;


