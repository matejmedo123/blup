  perform set_config('request.jwt.claim.sub', rival::text, true);
  perform public.cart_hold_seat(seat);
  assert exists (select 1 from public.cart_items
                 where venue_seat_id = seat and user_id = rival and expires_at > now()),
    'an abandoned checkout must release its seat';
  raise notice 'PASS a seat is not lost forever to somebody who closed the tab';

  delete from public.cart_items where venue_seat_id = seat;
end $$;


