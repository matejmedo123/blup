-- 1. The seat travels: basket -> order -> ticket
-- ============================================================================
do $$
declare
  buyer uuid := 'a3939393-0000-0000-0000-000000000002';
  rival uuid := 'a3939393-0000-0000-0000-000000000003';
  ev    uuid := 'd3939393-0000-0000-0000-000000000002';
  seat  uuid;
  co    public.checkouts;
  tick  public.tickets;
  map   jsonb;
  sect  jsonb;
  dot   jsonb;
begin
  select id into seat from public.venue_seats
  where venue_section_id = 'b3939393-0000-0000-0000-000000000001'
    and row_label = 'B' and seat_number = 3;

  perform set_config('request.jwt.claim.sub', buyer::text, true);
  perform public.cart_hold_seat(seat);

  co := public.create_checkout(buyer, null);

  -- The basket is gone — that is what create_checkout does — so if the seat
  -- lived only on the cart line, this is the moment it went back on sale.
  assert not exists (select 1 from public.cart_items where user_id = buyer),
    'the basket is emptied into the checkout';

  assert exists (
    select 1 from public.orders o
    where o.checkout_id = co.id and o.venue_seat_id = seat and o.quantity = 1
  ), 'the order names the seat';
  raise notice 'PASS the seat survives the basket becoming an order';

  -- And it is gone for the person refreshing the plan right now.
  perform set_config('request.jwt.claim.sub', rival::text, true);
  begin
    perform public.cart_hold_seat(seat);
    assert false, 'a seat on a live order must not be holdable';
  exception when others then
    assert sqlerrm = 'SEAT_TAKEN', format('expected SEAT_TAKEN, got %s', sqlerrm);
  end;
  raise notice 'PASS a seat being paid for is not on sale';

  -- ---- paid ------------------------------------------------------------------
  perform public.fulfill_checkout(co.id, 'stripe', 'pi_seat_39', co.total_cents);

  select * into tick from public.tickets t
  where t.event_id = ev and t.buyer_id = buyer limit 1;

  assert tick.venue_seat_id = seat,
    format('the ticket must name the seat, got %s', coalesce(tick.venue_seat_id::text, 'null'));
  raise notice 'PASS the paid ticket names the chair the buyer picked';

  -- ---- and the plan tells the buyer it is theirs ----------------------------
